# 1. التخصصات
# ══════════════════════════════════════════════
specializations = [
    "المعاملات المالية المعاصرة",
    "الفقه المقارن وأصوله",
    "الشريعة والقانون",
]

spec_ids = {}
for name in specializations:
    try:
        c.execute("INSERT INTO specializations (name) VALUES (?)", (name,))
        spec_ids[name] = c.lastrowid
    except sqlite3.IntegrityError:
        row = conn.execute("SELECT id FROM specializations WHERE name=?", (name,)).fetchone()
        spec_ids[name] = row[0]
        print(f"  [موجود] {name}")

conn.commit()
print(f"✅ التخصصات: {len(spec_ids)}")

